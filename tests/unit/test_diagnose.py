# -*- coding: utf-8 -*-
"""Unit: модуль диагностики (modules/diagnose) — парсеры и вердикт."""
from modules import diagnose


def test_parse_gateway_ok():
    out = ("default via 192.168.3.1 dev eth0 proto dhcp src 192.168.3.243 "
           "metric 100")
    assert diagnose.parse_gateway(out) == ("192.168.3.1", "eth0")


def test_parse_gateway_empty():
    assert diagnose.parse_gateway("") == (None, None)
    assert diagnose.parse_gateway(None) == (None, None)


def test_parse_iface_line():
    line = ("2: eth0    inet 192.168.3.243/24 brd 192.168.3.255 scope global "
            "dynamic eth0\\       valid_lft 86389sec preferred_lft 86389sec")
    assert diagnose.parse_iface_line(line) == ("eth0", "192.168.3.243/24")


def test_parse_iface_line_no_match():
    assert diagnose.parse_iface_line("2: eth0    inet6 fe80::1/64 scope link") is None


def test_parse_resolv():
    text = "; Generated by NetworkManager\nnameserver 192.168.3.1\nnameserver 8.8.8.8\n"
    assert diagnose.parse_resolv(text) == ["192.168.3.1", "8.8.8.8"]


def test_parse_ping_no_loss():
    out = """PING 192.168.3.1 (192.168.3.1) 56(84) bytes of data.
64 bytes from 192.168.3.1: icmp_seq=1 ttl=64 time=1.23 ms
64 bytes from 192.168.3.1: icmp_seq=2 ttl=64 time=1.50 ms
64 bytes from 192.168.3.1: icmp_seq=3 ttl=64 time=1.10 ms

--- 192.168.3.1 ping statistics ---
3 packets transmitted, 3 received, 0% packet loss, time 2003ms
rtt min/avg/max/mdev = 1.100/1.276/1.500/0.168 ms
"""
    st = diagnose.parse_ping(out)
    assert st["sent"] == 3 and st["recvd"] == 3
    assert st["loss_pct"] == 0.0
    assert st["min"] == 1.1 and st["avg"] == 1.276 and st["max"] == 1.5


def test_parse_ping_total_loss():
    out = """PING 8.8.8.8 (8.8.8.8) 56(84) bytes of data.

--- 8.8.8.8 ping statistics ---
5 packets transmitted, 0 received, 100% packet loss, time 4095ms
"""
    st = diagnose.parse_ping(out)
    assert st["sent"] == 5 and st["recvd"] == 0
    assert st["loss_pct"] == 100.0
    assert st["avg"] is None


def test_fmt_speed():
    assert diagnose.fmt_speed(12_500_000) == "100 Мбит/с"
    assert diagnose.fmt_speed(13_125_000) == "105 Мбит/с"
    assert diagnose.fmt_speed(3_125_000) == "25.0 Мбит/с"
    assert diagnose.fmt_speed(62_500) == "0.5 Мбит/с"


def test_verdict_all_ok():
    steps = [{"title": t, "status": s} for t, s in
             (("a", "ok"), ("b", "ok"), ("c", "skip"))]
    v = diagnose.verdict_of(steps)
    assert v["status"] == "ok" and "порядке" in v["text"]


def test_verdict_fail_wins():
    steps = [{"title": t, "status": s} for t, s in
             (("a", "ok"), ("b", "warn"), ("c", "fail"))]
    v = diagnose.verdict_of(steps)
    assert v["status"] == "fail" and "c" in v["text"]


def test_verdict_warn():
    steps = [{"title": t, "status": s} for t, s in
             (("a", "ok"), ("b", "warn"))]
    v = diagnose.verdict_of(steps)
    assert v["status"] == "warn"


def test_verdict_pending_empty():
    v = diagnose.verdict_of([])
    assert v["status"] == "pending"


def test_status_idle_shape():
    st = diagnose.status()
    assert st["running"] is False
    assert [s["id"] for s in st["steps"]] == [m["id"] for m in diagnose.STEPS]
    assert st["verdict"]["status"] == "pending"
